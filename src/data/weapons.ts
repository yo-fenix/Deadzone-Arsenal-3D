export function getCategoryStarterWeapons(): WeaponId[] {
  return WEAPONS.filter((w) => w.isCategoryStarter).map((w) => w.id);
}

/**
 * Picks a weapon strictly from the player's owned pool, weighted by rarity
 * (with melee weapons weighted extra high so they are the most common spawns).
 */
export function pickWeightedOwnedWeapon(ownedPool: WeaponId[]): WeaponId {
  const candidates = ownedPool.filter((id) => Boolean(WEAPON_MAP[id]));
  if (candidates.length === 0) return 'knife_combat';

  let totalWeight = 0;
  const weights = candidates.map((id) => {
    const spec = WEAPON_MAP[id];
    const baseWeight = RARITY_META[spec.rarity]?.dropWeight ?? 10;
    const typeFactor = spec.isMelee ? 3.8 : 0.48;
    const w = baseWeight * typeFactor;
    totalWeight += w;
    return w;
  });

  let roll = Math.random() * totalWeight;
  for (let i = 0; i < candidates.length; i++) {
    roll -= weights[i];
    if (roll <= 0) return candidates[i];
  }
  return candidates[0];
}

