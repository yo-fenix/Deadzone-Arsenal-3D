/**
 * Rolls a purchasable Mystery Crate that randomly awards a weapon (weighted by rarity) or NOTHING.
 * Firearms are noticeably rarer than melee weapons in crates.
 */
export function rollMysteryCrate(tier: CrateTier, ownedWeapons: WeaponId[]): CrateRollResult {
  const cfg = CRATE_TIERS[tier];
  if (Math.random() > cfg.winChance) {
    return { tier, wonWeapon: null, alreadyOwned: false, rebate: 0 };
  }

  const rarityWeights: Record<WeaponRarity, number> =
    tier === 'elite'
      ? { Común: 16, 'Poco Común': 30, Rara: 29, Épica: 17, Legendaria: 8 }
      : { Común: 50, 'Poco Común': 28, Rara: 14, Épica: 6, Legendaria: 2 };

  const ownedSet = new Set(ownedWeapons);
  let totalWeight = 0;
  const weights = WEAPONS.map((w) => {
    const rw = rarityWeights[w.rarity];
    const unownedBonus = ownedSet.has(w.id) ? 0.35 : 1.75;
    const typeFactor = w.isMelee ? (tier === 'elite' ? 1.5 : 2.9) : tier === 'elite' ? 0.82 : 0.36;
    const weight = rw * unownedBonus * typeFactor;
    totalWeight += weight;
    return weight;
  });

  let roll = Math.random() * totalWeight;
  let picked: WeaponId = WEAPONS[0].id;
  for (let i = 0; i < WEAPONS.length; i++) {
    roll -= weights[i];
    if (roll <= 0) {
      picked = WEAPONS[i].id;
      break;
    }
  }

  const alreadyOwned = ownedSet.has(picked);
  return {
    tier,
    wonWeapon: picked,
    alreadyOwned,
    rebate: alreadyOwned ? Math.round(cfg.creditCost * 0.45) : 0,
  };
}

/**
 * Rolls a random weapon inside physical military crates found during the match.
 * Rarity is strictly capped at Épica (never Legendaria).
 */
export function pickWorldCrateWeapon(alreadyUnlockedInRun: WeaponId[]): WeaponId | null {
  if (Math.random() > 0.78) return null;
  const unlockedSet = new Set(alreadyUnlockedInRun);
  const candidates = WEAPONS.filter(
    (w) => w.rarity !== 'Legendaria' && !unlockedSet.has(w.id)
  );
  if (candidates.length === 0) return null;

  let totalWeight = 0;
  const weights = candidates.map((w) => {
    const base = RARITY_META[w.rarity].dropWeight;
    const typeFactor = w.isMelee ? 1.55 : 0.9;
    const weight = base * typeFactor;
    totalWeight += weight;
    return weight;
  });

  let roll = Math.random() * totalWeight;
  for (let i = 0; i < candidates.length; i++) {
    roll -= weights[i];
    if (roll <= 0) return candidates[i].id;
  }
  return candidates[0].id;
}

/**
 * Boss kill reward: guarantees a scarce firearm not yet unlocked in the current run (or a high-tier weapon).
 */
export function pickBossRewardWeapon(alreadyUnlockedInRun: WeaponId[]): WeaponId | null {
  const unlockedSet = new Set(alreadyUnlockedInRun);
  const lockedFirearms = WEAPONS.filter((w) => !w.isMelee && !unlockedSet.has(w.id));
  const pool = lockedFirearms.length > 0 ? lockedFirearms : WEAPONS.filter((w) => !unlockedSet.has(w.id));
  if (pool.length === 0) return null;

  let totalWeight = 0;
  const weights = pool.map((w) => {
    const rw = w.rarity === 'Legendaria' ? 8 : w.rarity === 'Épica' ? 16 : w.rarity === 'Rara' ? 28 : 24;
    totalWeight += rw;
    return rw;
  });

  let roll = Math.random() * totalWeight;
  for (let i = 0; i < pool.length; i++) {
    roll -= weights[i];
    if (roll <= 0) return pool[i].id;
  }
  return pool[0].id;
}
